"""Independent regression oracle for the RO1b extraction (baseline 9137293).

The engine-vs-pure comparisons in ``test_availability_pure_equivalence.py``
prove only the DELEGATION wiring: the wrapper calls that very function, so a
rule change made inside the pure function is automatically adopted by the
wrapper and those comparisons would stay green. This file closes that gap
with an ORACLE INDEPENDENT of current production code:

1. ``reference_evaluate`` is a frozen, TEST-ONLY, literal copy of the
   decision ``AvailabilityEngine.evaluate`` made at baseline commit
   ``9137293387fb244ade516a73d9a2779ab5d6723a`` (pre-extraction), including
   frozen copies of its ``_parse_time``/``_effective_reserve`` helpers and of
   the missing-state default. It imports NO current production symbol to
   decide expected values. Attribution to the baseline is textual (this
   docstring/comment), so a shallow CI checkout works: no ``git``,
   subprocess or network is used by any test here.
2. ``MANUAL_BASELINE_CASES`` is a hand-written allowed/reason table derived
   from the pre-extraction contract (pause, window, refractory, budgets,
   reserve/threshold, legacy tolerances, priority order, essential, absent
   default, virtual recovery). No expected value was generated by running
   the current engine or pure function.
3. Mutation-demo tests sabotage the production rule TEMPORARILY through
   ``monkeypatch`` (no file is ever altered) and show that the delegation
   comparison keeps passing while this oracle fails -- proving the suite
   detects a rule/threshold/priority change even if pure function and
   wrapper change together.

The oracle lives only in tests; no production policy is duplicated outside
this file, and nothing here runs in production.
"""
