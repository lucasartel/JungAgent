_REFERENCE_DEFAULT_STATE = {
    "status": "available", "turn_budget": None, "turns_used": 0,
    "depth_budget": None, "depth_used": 0,
}


def _reference_parse_time(value):
    if not value:
        return None
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00")).replace(tzinfo=None)
    except ValueError:
        return None


def _reference_effective_reserve(state, now):
    reserve = float(state.get("relational_reserve") or 0)
    maximum = float(state.get("relational_reserve_max") or 100)
    last_exchange = _reference_parse_time(state.get("last_relational_exchange_at"))
    rate = float(state.get("relational_recovery_per_hour") or 0)
    if last_exchange and rate > 0:
        reserve += max(0.0, (now - last_exchange).total_seconds() / 3600) * rate
    return min(maximum, reserve)


def reference_evaluate(state, *, now, essential=False):
    """Frozen baseline-9137293 decision: ``{"allowed": bool, "reason": str|None}``.

    Literal copy of the pre-extraction ``AvailabilityEngine.evaluate``
    (state loading, essential bypass, priority order and reason strings).
    ``now`` must be an explicit instant (the baseline's ``_now`` strip of a
    naive value is identity; the clock fallback is intentionally not modeled
    because every test passes ``now``). Missing ``state`` reproduces the
    baseline default for a scope WITHOUT a row.
    """
    if state is None:
        state = dict(_REFERENCE_DEFAULT_STATE)
    if essential:
        return {"allowed": True, "reason": "essential_bypass"}
    instant = now.replace(tzinfo=None)
    if state.get("status") == "paused":
        return {"allowed": False, "reason": "availability_paused"}
    start = _reference_parse_time(state.get("contact_window_start_at"))
    end = _reference_parse_time(state.get("contact_window_end_at"))
    refractory = _reference_parse_time(state.get("refractory_until"))
    if start and instant < start:
        return {"allowed": False, "reason": "availability_window_not_open"}
    if end and instant >= end:
        return {"allowed": False, "reason": "availability_window_closed"}
    if refractory and instant < refractory:
        return {"allowed": False, "reason": "availability_refractory"}
    if state.get("turn_budget") is not None and int(state["turns_used"]) >= int(state["turn_budget"]):
        return {"allowed": False, "reason": "availability_turn_budget_exhausted"}
    if state.get("depth_budget") is not None and int(state["depth_used"]) >= int(state["depth_budget"]):
        return {"allowed": False, "reason": "availability_depth_budget_exhausted"}
    if (float(state.get("relational_reserve_threshold") or 0) > 0
            and _reference_effective_reserve(state, instant) <= float(state["relational_reserve_threshold"])):
        return {"allowed": False, "reason": "availability_relational_reserve_depleted"}
    return {"allowed": True, "reason": None}


def _pair(result):
    return (result["allowed"], result["reason"])


def _assert_matches_baseline_oracle(current, state, *, now, essential=False):
    frozen = reference_evaluate(state, now=now, essential=essential)
    assert _pair(current) == _pair(frozen), (
        "baseline-oracle-mismatch: current=(%r, %r) baseline-9137293=(%r, %r)"
        % (current["allowed"], current["reason"],
           frozen["allowed"], frozen["reason"]))


# ---------------------------------------------------------------------------
# 1) Frozen oracle over the existing equivalence matrix (aggregated on
#    purpose: no hundreds of parametrizations without new meaning).
# ---------------------------------------------------------------------------

def test_frozen_oracle_over_the_whole_equivalence_matrix():
    mismatches = []
    for param in EQUIVALENCE_STATES:
        state = param.values[0]
        for instant in INSTANTS:
            for essential in (False, True):
                current = AvailabilityEngine(_StateDB(state)).evaluate(
                    SCOPE, now=instant, essential=essential)
                frozen = reference_evaluate(dict(state), now=instant,
                                            essential=essential)
                if _pair(current) != _pair(frozen):
                    mismatches.append(
                        (param.id, instant.isoformat(), essential,
                         _pair(current), _pair(frozen)))
    assert mismatches == []


def test_frozen_oracle_over_the_legacy_missing_state_default():
    current = AvailabilityEngine(_StateDB(None)).evaluate(SCOPE, now=AT13)
    frozen = reference_evaluate(None, now=AT13)
    assert _pair(current) == _pair(frozen) == (True, None)
    # The default DICTIONARY itself is also part of the frozen contract.
    assert current["state"] == _REFERENCE_DEFAULT_STATE


