@pytest.mark.parametrize(
    "state, now, essential, expected_allowed, expected_reason",
    MANUAL_BASELINE_CASES,
)
def test_manual_baseline_expectation_holds(state, now, essential,
                                           expected_allowed, expected_reason):
    current = AvailabilityEngine(_StateDB(state)).evaluate(
        SCOPE, now=now, essential=essential)
    assert _pair(current) == (expected_allowed, expected_reason)
    if state is not None:
        pure = evaluate_availability_state(dict(state), now=now,
                                           essential=essential)
        assert _pair(pure) == (expected_allowed, expected_reason)
    # The frozen oracle must agree with the hand-written expectation too.
    frozen = reference_evaluate(
        dict(state) if state is not None else None, now=now,
        essential=essential)
    assert _pair(frozen) == (expected_allowed, expected_reason)


# ---------------------------------------------------------------------------
# 3) Mutation demos: the delegation comparison stays green while a rule or
#    priority change (adopted by BOTH pure function and wrapper) is caught
#    by the frozen oracle. Production files are never altered: the sabotage
#    exists only for the duration of the test via monkeypatch.
# ---------------------------------------------------------------------------

def test_oracle_catches_a_rule_change_that_pure_and_wrapper_agree_on(
        monkeypatch):
    # Baseline expectation for this state: reserve 10 <= threshold 15.
    state = _state(relational_reserve=10.0)

    def _sabotaged_rule(state_, *, now, essential=False):
        # Simulated unauthorized change: the reserve rule simply disappears.
        if essential:
            return {"allowed": True, "reason": "essential_bypass"}
        if state_.get("status") == "paused":
            return {"allowed": False, "reason": "availability_paused"}
        return {"allowed": True, "reason": None}

    monkeypatch.setattr(availability_module, "evaluate_availability_state",
                        _sabotaged_rule)
    engine = AvailabilityEngine(_StateDB(state))
    current = engine.evaluate(SCOPE, now=AT13)
    # Delegation-style comparison (wrapper vs CURRENT pure) still passes:
    assert current == {**_sabotaged_rule(dict(state), now=AT13),
                       "state": state}
    # The frozen baseline oracle detects the regression anyway:
    with pytest.raises(AssertionError, match="baseline-oracle-mismatch"):
        _assert_matches_baseline_oracle(current, dict(state), now=AT13)


def test_oracle_catches_a_priority_change_that_pure_and_wrapper_agree_on(
        monkeypatch):
    state = _state(status="paused")

    def _sabotaged_priority(state_, *, now, essential=False):
        # Simulated unauthorized change: pause no longer wins first.
        if essential:
            return {"allowed": True, "reason": "essential_bypass"}
        if state_.get("status") == "paused":
            return {"allowed": False,
                    "reason": "availability_window_not_open"}
        return {"allowed": True, "reason": None}

    monkeypatch.setattr(availability_module, "evaluate_availability_state",
                        _sabotaged_priority)
    engine = AvailabilityEngine(_StateDB(state))
    current = engine.evaluate(SCOPE, now=AT13)
    assert current == {**_sabotaged_priority(dict(state), now=AT13),
                       "state": state}
    with pytest.raises(AssertionError, match="baseline-oracle-mismatch"):
        _assert_matches_baseline_oracle(current, dict(state), now=AT13)
